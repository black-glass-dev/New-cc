#!/usr/bin/env python3
"""Compile engine/color/shaders/*.comp to SPIR-V and embed them as a C++ header.

Usage:
  python3 scripts/build_color_shaders.py --glslang /path/to/glslangValidator   # regenerate
  python3 scripts/build_color_shaders.py --check                               # no compiler needed

The generated header records the SHA-256 of the GLSL source it was built from. --check fails when the
source changed without regenerating the SPIR-V, so the committed binary cannot silently drift.
Target environment is Vulkan 1.0 (storage images, push constants), the widest phone baseline.
"""
import argparse
import hashlib
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHADER_DIR = ROOT / 'engine/color/shaders'
OUT_DIR = SHADER_DIR / 'generated'
SHADERS = [
    # (source file, C++ identifier prefix)
    ('exposure_fp32.comp', 'kExposureFp32'),
    ('grade_fp32.comp', 'kGradeFp32'),
]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def header_path(source: str) -> Path:
    return OUT_DIR / (Path(source).stem + '_spv.inc')


def write_header(source: str, prefix: str, spirv: bytes, digest: str) -> None:
    words = struct.unpack('<%dI' % (len(spirv) // 4), spirv)
    lines = [
        '// Generated by scripts/build_color_shaders.py. Do not edit.',
        '// source: engine/color/shaders/%s' % source,
        '// source-sha256: %s' % digest,
        '#pragma once',
        '#include <cstdint>',
        '',
        'namespace editor::color::vulkan::generated {',
        '',
        'inline constexpr char %sSourceSha256[] = "%s";' % (prefix, digest),
        'inline constexpr std::uint32_t %sSpirv[] = {' % prefix,
    ]
    for i in range(0, len(words), 8):
        lines.append('    ' + ', '.join('0x%08xu' % w for w in words[i:i + 8]) + ',')
    lines += ['};', '', '}  // namespace editor::color::vulkan::generated', '']
    header_path(source).write_text('\n'.join(lines))


def compile_shader(glslang: str, source: Path) -> bytes:
    with tempfile.TemporaryDirectory(prefix='owncut-spv-') as tmp:
        out = Path(tmp) / 'out.spv'
        subprocess.run([glslang, '-V', '--target-env', 'vulkan1.0', '-S', 'comp', str(source), '-o', str(out)],
                       check=True)
        return out.read_bytes()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--glslang', help='path to glslangValidator (required unless --check)')
    parser.add_argument('--check', action='store_true', help='verify committed headers match the sources')
    args = parser.parse_args()

    if args.check:
        ok = True
        for source, prefix in SHADERS:
            digest = sha256(SHADER_DIR / source)
            header = header_path(source)
            if not header.exists() or ('// source-sha256: %s' % digest) not in header.read_text():
                print('STALE: %s changed; rerun build_color_shaders.py --glslang ...' % source)
                ok = False
            else:
                print('ok: %s matches %s' % (source, header.relative_to(ROOT)))
        return 0 if ok else 1

    glslang = args.glslang or shutil.which('glslangValidator')
    if not glslang:
        print('glslangValidator not found; pass --glslang', file=sys.stderr)
        return 2
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for source, prefix in SHADERS:
        path = SHADER_DIR / source
        spirv = compile_shader(glslang, path)
        write_header(source, prefix, spirv, sha256(path))
        print('wrote %s (%d bytes SPIR-V)' % (header_path(source).relative_to(ROOT), len(spirv)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
